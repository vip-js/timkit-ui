const createPreviewComponent = (name: keyof typeof previewComponentManifest) =>
  dynamic(
    () =>
      previewComponentManifest[name]().then((mod) => ({
        default: (mod as any).default || mod,
      })),
    {
      ssr: false,
      loading: () => null,
    }
  )

