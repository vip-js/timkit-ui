const fs = require('fs')
const path = require('path')

const resolveRepoRoot = () => {
  const candidates = [
    process.cwd(),
    path.resolve(process.cwd(), '..'),
    path.resolve(process.cwd(), '..', '..'),
  ]
  return (
    candidates.find((candidate) => fs.existsSync(path.join(candidate, 'apps/docs/registry'))) ||
    process.cwd()
  )
}

const REPO_ROOT = resolveRepoRoot()
const REGISTRY_INDEX = path.join(REPO_ROOT, 'apps/docs/data/registry-index.json')
const OUTPUT = path.join(REPO_ROOT, 'apps/docs/registry/registry-manifest.ts')

const toPosix = (value) => value.replace(/\\/g, '/')

const registryRoot = path.join(REPO_ROOT, 'apps/docs')
const registryIndex = JSON.parse(fs.readFileSync(REGISTRY_INDEX, 'utf-8'))
function walkTsxFiles(rootDir) {
  if (!fs.existsSync(rootDir)) return []
  const entries = fs.readdirSync(rootDir, { withFileTypes: true })
  return entries.flatMap((entry) => {
    const fullPath = path.join(rootDir, entry.name)
    if (entry.isDirectory()) return walkTsxFiles(fullPath)
    if (entry.isFile() && entry.name.endsWith('.tsx')) {
      return [toPosix(path.relative(registryRoot, fullPath))]
    }
    return []
  })
}

const files = Array.from(
  new Set([
    ...(registryIndex.items || [])
      .flatMap((item) => {
        const itemFiles = item.files || []
        const previewPath =
          item.meta && typeof item.meta.previewPath === 'string' ? item.meta.previewPath : ''
        return [...itemFiles.map((file) => file.path), previewPath]
      })
      .filter((filePath) => typeof filePath === 'string' && filePath.endsWith('.tsx'))
      .filter((filePath) => filePath.startsWith('registry/'))
      .filter((filePath) => fs.existsSync(path.join(registryRoot, filePath))),
    ...walkTsxFiles(path.join(registryRoot, 'registry/default/blocks')),
    ...walkTsxFiles(path.join(registryRoot, 'registry/default/templates')),
  ])
)

const entries = files
  .map((filePath) => {
    const relFromDocs = toPosix(path.relative(registryRoot, path.join(registryRoot, filePath)))
    const importPath = relFromDocs.endsWith('.tsx')
      ? `@/${relFromDocs.slice(0, -4)}`
      : `@/${relFromDocs}`
    return { key: relFromDocs, importPath }
  })
  .filter(Boolean)
  .sort((a, b) => a.key.localeCompare(b.key))

const lines = [
  '/* eslint-disable */',
  '// This file is auto-generated by scripts/generate-docs-registry-manifest.cjs',
  '// Do not edit manually.',
  '',
  'export const registryComponentManifest = {',
  ...entries.map((entry) => `  '${entry.key}': () => import('${entry.importPath}'),`),
  '} as const',
  '',
]

fs.writeFileSync(OUTPUT, `${lines.join('\n')}\n`, 'utf-8')
console.log(`registry manifest written: ${entries.length} entries -> ${OUTPUT}`)
