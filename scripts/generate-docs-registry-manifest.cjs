const fs = require('fs')
const path = require('path')

const resolveRepoRoot = () => {
  const candidates = [
    process.cwd(),
    path.resolve(process.cwd(), '..'),
    path.resolve(process.cwd(), '..', '..'),
  ]
  return (
    candidates.find((candidate) =>
      fs.existsSync(path.join(candidate, 'apps/docs/registry'))
    ) || process.cwd()
  )
}

const REPO_ROOT = resolveRepoRoot()
const ROOT = path.join(REPO_ROOT, 'apps/docs/registry')
const OUTPUT = path.join(REPO_ROOT, 'apps/docs/registry/registry-manifest.ts')

const toPosix = (value) => value.replace(/\\/g, '/')

const walk = (dir, acc = []) => {
  const entries = fs.readdirSync(dir, { withFileTypes: true })
  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name)
    if (entry.isDirectory()) {
      walk(fullPath, acc)
      continue
    }
    if (entry.isFile() && entry.name.endsWith('.tsx')) {
      acc.push(fullPath)
    }
  }
  return acc
}

const registryRoot = path.join(REPO_ROOT, 'apps/docs')
const files = walk(ROOT)

const entries = files
  .map((filePath) => {
    const relFromDocs = toPosix(path.relative(registryRoot, filePath))
    if (!relFromDocs.startsWith('registry/')) return null
    const importPath = relFromDocs.endsWith('.tsx')
      ? `@/${relFromDocs.slice(0, -4)}`
      : `@/${relFromDocs}`
    return { key: relFromDocs, importPath }
  })
  .filter(Boolean)
  .sort((a, b) => a.key.localeCompare(b.key))

const lines = [
  '/* eslint-disable */',
  '// This file is auto-generated by scripts/generate-docs-registry-manifest.cjs',
  '// Do not edit manually.',
  '',
  'export const registryComponentManifest = {',
  ...entries.map((entry) => `  '${entry.key}': () => import('${entry.importPath}'),`),
  '} as const',
  '',
]

fs.writeFileSync(OUTPUT, `${lines.join('\n')}\n`, 'utf-8')
console.log(`registry manifest written: ${entries.length} entries -> ${OUTPUT}`)
