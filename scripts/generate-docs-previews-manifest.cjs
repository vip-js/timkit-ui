const fs = require('fs')
const path = require('path')

const resolveRepoRoot = () => {
  const candidates = [
    process.cwd(),
    path.resolve(process.cwd(), '..'),
    path.resolve(process.cwd(), '..', '..'),
  ]
  return (
    candidates.find((candidate) =>
      fs.existsSync(path.join(candidate, 'apps/docs/previews'))
    ) || process.cwd()
  )
}

const REPO_ROOT = resolveRepoRoot()
const PREVIEWS_DIR = path.join(REPO_ROOT, 'apps/docs/previews')
const OUTPUT = path.join(REPO_ROOT, 'apps/docs/previews/preview-manifest.ts')

const toPosix = (value) => value.replace(/\\/g, '/')

const files = fs
  .readdirSync(PREVIEWS_DIR, { withFileTypes: true })
  .filter((entry) => entry.isFile() && /\.(jsx|tsx)$/.test(entry.name))
  .map((entry) => entry.name)
  .sort()

const entries = files.map((file) => {
  const name = file.replace(/\.(jsx|tsx)$/, '')
  const relFromDocs = toPosix(path.join('previews', file))
  const importPath = `@/${relFromDocs.replace(/\.(jsx|tsx)$/, '')}`
  return { name, importPath }
})

const lines = [
  '/* eslint-disable */',
  '// This file is auto-generated by scripts/generate-docs-previews-manifest.cjs',
  '// Do not edit manually.',
  '',
  'export const previewComponentManifest = {',
  ...entries.map(
    (entry) => `  '${entry.name}': () => import('${entry.importPath}'),`
  ),
  '} as const',
  '',
]

fs.writeFileSync(OUTPUT, `${lines.join('\n')}\n`, 'utf-8')
console.log(`preview manifest written: ${entries.length} entries -> ${OUTPUT}`)
