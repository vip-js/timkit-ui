#!/usr/bin/env node

const fs = require('fs')
const path = require('path')

const ROOT = path.resolve(__dirname, '..')
const DOCS_COMPONENTS_ROOT = path.join(ROOT, 'apps/docs/registry/default/components')
const VUE_UI_ROOT = path.join(ROOT, 'packages/vue/src/components/ui')
const IMPORT_RE = /from\s+['"]@\/components\/ui\/([^'"/]+)['"]/g
const AUTO_MARKER = '// AUTO-GENERATED BY scripts/generate-vue-ui-token-entries.cjs'

function walkFiles(rootDir, predicate) {
  if (!fs.existsSync(rootDir)) return []
  const result = []
  const stack = [rootDir]
  while (stack.length > 0) {
    const current = stack.pop()
    const entries = fs.readdirSync(current, { withFileTypes: true })
    for (const entry of entries) {
      const full = path.join(current, entry.name)
      if (entry.isDirectory()) {
        stack.push(full)
        continue
      }
      if (entry.isFile() && predicate(full)) {
        result.push(full)
      }
    }
  }
  return result
}

function toPascalCase(value) {
  return value
    .split('-')
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('')
}

function collectTokens() {
  const vueFiles = walkFiles(DOCS_COMPONENTS_ROOT, (file) => file.endsWith('.vue'))
  const tokens = new Set()

  for (const file of vueFiles) {
    const source = fs.readFileSync(file, 'utf8')
    let match
    while ((match = IMPORT_RE.exec(source))) {
      tokens.add(match[1])
    }
    IMPORT_RE.lastIndex = 0
  }

  return Array.from(tokens).sort()
}

function buildVueFileIndex() {
  const vueFiles = walkFiles(VUE_UI_ROOT, (file) => file.endsWith('.vue'))
  const byBaseName = new Map()

  for (const abs of vueFiles) {
    const baseName = path.basename(abs, '.vue')
    if (!byBaseName.has(baseName)) byBaseName.set(baseName, [])
    byBaseName.get(baseName).push(abs)
  }

  return { vueFiles, byBaseName }
}

function createEntrySourceForToken(token, byBaseName) {
  const folder = path.join(VUE_UI_ROOT, token)
  const lines = [AUTO_MARKER]

  if (fs.existsSync(folder) && fs.statSync(folder).isDirectory()) {
    const vueFiles = fs
      .readdirSync(folder)
      .filter((f) => f.endsWith('.vue'))
      .sort()

    if (vueFiles.length === 0) return null

    const sameName = `${token}.vue`
    if (vueFiles.includes(sameName)) {
      lines.push(`export { default } from './${token}/${sameName}'`)
    }

    for (const file of vueFiles) {
      const baseName = path.basename(file, '.vue')
      lines.push(`export { default as ${toPascalCase(baseName)} } from './${token}/${file}'`)
    }

    return `${lines.join('\n')}\n`
  }

  const candidates = byBaseName.get(token) || []
  if (candidates.length === 0) return null

  // Prefer non-top-level component files when both wrapper and real implementation exist.
  const topLevelVue = path.join(VUE_UI_ROOT, `${token}.vue`)
  const target = candidates.find((candidate) => candidate !== topLevelVue) || candidates[0]
  const rel = `./${path.relative(VUE_UI_ROOT, target).replace(/\\/g, '/')}`
  lines.push(`export { default } from '${rel}'`)
  lines.push(`export { default as ${toPascalCase(token)} } from '${rel}'`)
  return `${lines.join('\n')}\n`
}

function shouldWriteEntry(filePath) {
  if (!fs.existsSync(filePath)) return true
  const current = fs.readFileSync(filePath, 'utf8')
  return current.includes(AUTO_MARKER)
}

function main() {
  const tokens = collectTokens()
  const { byBaseName } = buildVueFileIndex()

  let written = 0
  let skipped = 0
  let unresolved = 0
  let unresolvedButExisting = 0
  const unresolvedTokens = []

  for (const token of tokens) {
    const entryPath = path.join(VUE_UI_ROOT, `${token}.ts`)
    const source = createEntrySourceForToken(token, byBaseName)
    if (!source) {
      if (fs.existsSync(entryPath)) {
        unresolvedButExisting += 1
        continue
      }
      unresolved += 1
      unresolvedTokens.push(token)
      continue
    }

    if (!shouldWriteEntry(entryPath)) {
      skipped += 1
      continue
    }

    fs.writeFileSync(entryPath, source, 'utf8')
    written += 1
  }

  // eslint-disable-next-line no-console
  console.log(
    `[vue-ui-entries] tokens=${tokens.length} written=${written} skipped=${skipped} unresolved_existing=${unresolvedButExisting} unresolved=${unresolved}`
  )
  if (unresolved > 0) {
    console.error(`Unresolved tokens: ${unresolvedTokens.join(', ')}`)
    process.exitCode = 1
  }
}

main()
