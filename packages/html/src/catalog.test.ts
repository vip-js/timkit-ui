import fs from 'node:fs'
import path from 'node:path'
import { describe, expect, it } from 'vitest'

const dir = path.resolve(__dirname, 'components')
const files = fs
  .readdirSync(dir)
  .filter((file) => file.endsWith('.html'))
  .sort()

